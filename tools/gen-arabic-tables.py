#!/usr/bin/env python3
"""Generate mod/rtl/src/arabic-tables.ts.

Inputs: Python's unicodedata (presentation-form decompositions) and ArabicShaping.txt of the same
Unicode version (joining types), e.g. https://www.unicode.org/Public/15.0.0/ucd/ArabicShaping.txt
Usage: python3 tools/gen-arabic-tables.py ArabicShaping.txt > mod/rtl/src/arabic-tables.ts
"""
import re, sys, unicodedata as u

shaping = open(sys.argv[1], encoding='utf-8').read()
m = re.search(r'ArabicShaping-(\d+\.\d+\.\d+)\.txt', shaping)
if not m or m.group(1) != u.unidata_version:
    sys.exit(f'version mismatch: ArabicShaping {m and m.group(1)} vs unicodedata {u.unidata_version}')

forms, lig = {}, {}
for cp in list(range(0xFB50, 0xFE00)) + list(range(0xFE70, 0xFF00)):
    d = u.decomposition(chr(cp))
    if not d.startswith('<'):
        continue
    tag, *rest = d.split()
    idx = {'<isolated>': 0, '<final>': 1, '<initial>': 2, '<medial>': 3}.get(tag)
    if idx is None:
        continue
    rest = [int(x, 16) for x in rest]
    if len(rest) == 1:
        f = forms.setdefault(rest[0], [0, 0, 0, 0])
        if not f[idx]:
            f[idx] = cp
    elif len(rest) == 2 and rest[0] == 0x644 and rest[1] in (0x622, 0x623, 0x625, 0x627) and idx < 2:
        lig.setdefault(rest[1], [0, 0])[idx] = cp

types = {}
for line in shaping.splitlines():
    line = line.split('#')[0].strip()
    if not line:
        continue
    f = [x.strip() for x in line.split(';')]
    types[int(f[0], 16)] = f[2]
ranges = []
for cp in sorted(types):
    t = types[cp]
    if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == t:
        ranges[-1][1] = cp
    else:
        ranges.append([cp, cp, t])

code = {'U': 0, 'D': 1, 'R': 2, 'L': 3, 'C': 4, 'T': 5}
out = [f'// Generated by tools/gen-arabic-tables.py from Unicode {u.unidata_version} data. Do not edit by hand.',
       '// FORMS: base letter, then its isolated, final, initial and medial presentation forms (0 = none),',
       '// from the <isolated>/<final>/<initial>/<medial> decompositions of U+FB50-FDFF and U+FE70-FEFF.',
       'export const FORMS: number[] = [']
items = sorted(forms.items())
for i in range(0, len(items), 4):
    out.append('  ' + ' '.join('0x%04x, 0x%04x, 0x%04x, 0x%04x, 0x%04x,' % (k, *v) for k, v in items[i:i + 4]))
out += [']', '// LAM_ALEF: alef variant, then the isolated and final forms of lam + that alef.', 'export const LAM_ALEF: number[] = [']
for k, v in sorted(lig.items()):
    out.append('  0x%04x, 0x%04x, 0x%04x,' % (k, *v))
out += [']',
        '// JOINING: inclusive ranges with their explicit Joining_Type from ArabicShaping.txt:',
        '// start, end, type (0 U, 1 D, 2 R, 3 L, 4 C, 5 T). Unlisted Mn, Me and Cf are T; the rest U.',
        'export const JOINING: number[] = [']
for i in range(0, len(ranges), 6):
    out.append('  ' + ' '.join('0x%04x, 0x%04x, %d,' % (a, b, code[t]) for a, b, t in ranges[i:i + 6]))
out.append(']')
print('\n'.join(out))
